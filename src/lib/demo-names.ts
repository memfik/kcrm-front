/** Псевдослучайное число от ID и номера поля — одно и то же для одной записи. */
export const rnd = (id: number | string, k: number) => {
  let x = ((+id || 0) * 2654435761 + k * 40503) >>> 0
  x ^= x >>> 15
  x = (x * 2246822519) >>> 0
  x ^= x >>> 13
  return x >>> 0
}
export const pick = <T,>(a: readonly T[], id: number | string, k: number) => a[rnd(id, k) % a.length]

